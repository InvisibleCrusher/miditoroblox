#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum InstrumentType {
    Other,
    Piano,
    Guitar,
    Bass,
    Strings,
    Brass,
    Synth,
    Drum,
}

impl InstrumentType {
    pub fn label(&self) -> &'static str {
        match self {
            InstrumentType::Other => "Other",
            InstrumentType::Piano => "Piano",
            InstrumentType::Guitar => "Guitar",
            InstrumentType::Bass => "Bass",
            InstrumentType::Strings => "Strings",
            InstrumentType::Brass => "Brass",
            InstrumentType::Synth => "Synth",
            InstrumentType::Drum => "Drum",
        }
    }

    pub fn all() -> &'static [InstrumentType] {
        &[
            InstrumentType::Other,
            InstrumentType::Piano,
            InstrumentType::Guitar,
            InstrumentType::Bass,
            InstrumentType::Strings,
            InstrumentType::Brass,
            InstrumentType::Synth,
            InstrumentType::Drum,
        ]
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub struct InstrumentSlot {
    pub enabled: bool,
    pub inst_type: InstrumentType,
    pub min_note: u8,
    pub max_note: u8,
    pub transposition: i8,
}

pub fn match_instrument(channel: u8, program: u8, target: InstrumentType) -> bool {
    if channel == 9 {
        return target == InstrumentType::Drum;
    }
    match target {
        InstrumentType::Piano => program <= 23,
        InstrumentType::Guitar => (24..=31).contains(&program),
        InstrumentType::Bass => (32..=39).contains(&program),
        InstrumentType::Strings => (40..=55).contains(&program),
        InstrumentType::Brass => (56..=79).contains(&program),
        InstrumentType::Synth => (80..=103).contains(&program),
        InstrumentType::Drum => (112..=119).contains(&program),
        InstrumentType::Other => (program > 103 && program < 112) || program > 119,
    }
}

